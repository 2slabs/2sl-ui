#!/usr/bin/env python3
"""Checks tokens.css and writes what is derived from it. Stdlib only.

    python3 scripts/derived_tokens.py           # check tokens.css, rewrite max/2sl-colors.json
    python3 scripts/derived_tokens.py --check   # check tokens.css, fail if max/2sl-colors.json is stale

What it checks (any failure stops with a message naming the token):
  - tokens.css parses the way consumers parse it: a `:root {` block (light) and a
    `:root[data-theme="dark"]` block whose tokens all exist in the light one, and every colour a
    literal #RRGGBB (LPX Grid's app/sync_2sl_ui.py reads the file with the same rules).
  - the Launchpad hues equal the rule in README "Launchpad hues", computed from the LED values
    below (copied from LPX_Script's palette.py; if that checkout is beside this repo, or
    LPX_SCRIPT_DIR points at it, the copy is checked against it too).

max/2sl-colors.json is every colour token in both themes as Max RGBA floats. Never edit it by
hand: it is generated here, and scripts/sync.sh runs the check before copying anything.
"""

from __future__ import annotations

import json
import os
import re
import runpy
import sys
from pathlib import Path

REPOSITORY_DIRECTORY = Path(__file__).resolve().parent.parent
TOKENS_CSS_PATH = REPOSITORY_DIRECTORY / "tokens.css"
MAX_COLOURS_JSON_PATH = REPOSITORY_DIRECTORY / "max" / "2sl-colors.json"
DEFAULT_LPX_SCRIPT_DIRECTORY = REPOSITORY_DIRECTORY.parent / "LPX_Script"

LIGHT_BLOCK_PATTERN = re.compile(r"^:root\s*\{(?P<body>.*?)^\}", re.S | re.M)
DARK_BLOCK_PATTERN = re.compile(r'^:root\[data-theme="dark"\][^{]*\{(?P<body>.*?)^\}', re.S | re.M)
DECLARATION_PATTERN = re.compile(r"--(?P<name>[a-z0-9-]+)\s*:\s*(?P<value>[^;]+);")
HEX_COLOUR_PATTERN = re.compile(r"^#[0-9A-F]{6}$")

# LPX_Script palette.py SNAPSHOT_ROW_HUES_TOP_TO_BOTTOM: Launchpad LED values, 0..127 per channel.
LAUNCHPAD_ROW_HUES_TOP_TO_BOTTOM = [
    ("red", (127, 0, 0)),
    ("orange", (127, 40, 0)),
    ("yellow", (127, 110, 0)),
    ("green", (0, 127, 0)),
    ("cyan", (0, 127, 127)),
    ("blue", (0, 0, 127)),
    ("purple", (70, 0, 127)),
    ("pink", (127, 0, 70)),
]
LED_CHANNEL_MAX = 127
DARK_HUE_BRIGHTEST_CHANNEL = 0x6A  # dark hue = lit colour scaled so its brightest channel is 0x6A
# Dark hues that predate the written rule and are kept because consumers depend on them
# (README "Launchpad hues"). A new hue never goes here.
DARK_HUES_KEPT_OFF_RULE = {
    "orange": "#6A2300",  # the rule gives #6A2100: green channel 2/255 brighter, invisible
    "green": "#005A00",   # the rule gives #006A00: dimmed by hand, pure green reads brightest
}
MAX_JSON_COMMENT = ("GENERATED by scripts/derived_tokens.py from tokens.css: do not edit. 2sl-ui colours as Max RGBA "
                     "floats (0-1) for Max for Live: paste into live.* / panel / comment colour attributes, or load "
                     "with [dict]. Same names as tokens.css; 'dark' is the full dark theme (light values where dark "
                     "doesn't override).")


class TokenError(Exception):
    pass


def declarations_in_block(css_text: str, pattern: re.Pattern, block_name: str) -> dict[str, str]:
    match = pattern.search(css_text)
    if match is None:
        raise TokenError(f"tokens.css: no {block_name} block found")
    declarations: dict[str, str] = {}
    for declaration in DECLARATION_PATTERN.finditer(match.group("body")):
        name = declaration.group("name")
        if name in declarations:
            raise TokenError(f"tokens.css: --{name} declared twice in the {block_name} block")
        declarations[name] = declaration.group("value").strip()
    return declarations


def read_colour_themes(css_text: str) -> tuple[dict[str, str], dict[str, str]]:
    """(light colours, dark colours) as #RRGGBB in tokens.css order. Dark = light + dark overrides."""
    light_declarations = declarations_in_block(css_text, LIGHT_BLOCK_PATTERN, ":root")
    dark_overrides = declarations_in_block(css_text, DARK_BLOCK_PATTERN, ':root[data-theme="dark"]')
    dark_only_tokens = sorted(set(dark_overrides) - set(light_declarations))
    if dark_only_tokens:
        raise TokenError(f"tokens.css: the dark theme sets tokens the light one lacks: {dark_only_tokens}")
    colours_by_theme = []
    for theme_name, declarations in (("light", light_declarations), ("dark", {**light_declarations, **dark_overrides})):
        colours = {}
        for name, value in declarations.items():
            if not value.startswith("#"):
                continue  # type, space and layout tokens
            if not HEX_COLOUR_PATTERN.match(value):
                raise TokenError(f"tokens.css: --{name} ({theme_name}) is '{value}': colours must be #RRGGBB, upper case")
            colours[name] = value
        colours_by_theme.append(colours)
    light_colours, dark_colours = colours_by_theme
    overridden_non_colours = [name for name in dark_overrides if name not in dark_colours]
    if overridden_non_colours:
        raise TokenError(f"tokens.css: the dark theme overrides non-colour tokens {overridden_non_colours}")
    return light_colours, dark_colours


def screen_channel(led_value: int) -> int:
    """A Launchpad LED value (0..127) as an 8-bit screen channel: LPX Grid's GridModel screenChannel."""
    return led_value * 255 // LED_CHANNEL_MAX


def hex_colour(channels: tuple[int, int, int] | list[int]) -> str:
    return "#" + "".join(f"{channel:02X}" for channel in channels)


def expected_launchpad_hues() -> dict[str, tuple[str, str, str]]:
    """hue name -> (light, dark, lit) by README "Launchpad hues"."""
    expected = {}
    for hue_name, led_colour in LAUNCHPAD_ROW_HUES_TOP_TO_BOTTOM:
        lit = [screen_channel(channel) for channel in led_colour]
        light = [screen_channel(channel // 4) for channel in led_colour]  # palette.py quarter_brightness
        dark = [round(channel * DARK_HUE_BRIGHTEST_CHANNEL / 0xFF) for channel in lit]
        expected[hue_name] = (hex_colour(light), DARK_HUES_KEPT_OFF_RULE.get(hue_name, hex_colour(dark)), hex_colour(lit))
    return expected


def check_launchpad_hues(light_colours: dict[str, str], dark_colours: dict[str, str]) -> None:
    problems = []
    for hue_name, (light, dark, lit) in expected_launchpad_hues().items():
        for token_name, theme_name, colours, expected in (
            (f"hue-{hue_name}", "light", light_colours, light),
            (f"hue-{hue_name}", "dark", dark_colours, dark),
            (f"hue-{hue_name}-lit", "light", light_colours, lit),
            (f"hue-{hue_name}-lit", "dark", dark_colours, lit),
        ):
            actual = colours.get(token_name)
            if actual != expected:
                problems.append(f"--{token_name} ({theme_name}) is {actual}, the rule gives {expected}")
    if problems:
        raise TokenError("tokens.css: Launchpad hues off the rule (README \"Launchpad hues\"):\n  " + "\n  ".join(problems))


def check_led_values_against_palette_py() -> str:
    """Compares LAUNCHPAD_ROW_HUES_TOP_TO_BOTTOM with palette.py when it is checked out. Returns a status line."""
    lpx_script_directory = Path(os.environ.get("LPX_SCRIPT_DIR", DEFAULT_LPX_SCRIPT_DIRECTORY)).expanduser()
    palette_path = lpx_script_directory / "palette.py"
    if not palette_path.is_file():
        return f"note: {palette_path} not found, Launchpad LED values not re-checked against palette.py (set LPX_SCRIPT_DIR)"
    palette_hues = runpy.run_path(str(palette_path))["SNAPSHOT_ROW_HUES_TOP_TO_BOTTOM"]
    ours = tuple(led_colour for _, led_colour in LAUNCHPAD_ROW_HUES_TOP_TO_BOTTOM)
    if tuple(palette_hues) != ours:
        raise TokenError(f"{palette_path}: SNAPSHOT_ROW_HUES_TOP_TO_BOTTOM is {palette_hues}, 2sl-ui has {ours}; "
                         "palette.py is the hues' source: update LAUNCHPAD_ROW_HUES_TOP_TO_BOTTOM and tokens.css")
    return f"Launchpad LED values match {palette_path}"


def max_float(channel_hex: str) -> float:
    return round(int(channel_hex, 16) / 255, 3)


def max_colours_json_text(light_colours: dict[str, str], dark_colours: dict[str, str]) -> str:
    lines = ["{", f"  {json.dumps('_comment')}: {json.dumps(MAX_JSON_COMMENT)},"]
    for theme_index, (theme_name, colours) in enumerate((("light", light_colours), ("dark", dark_colours))):
        lines.append(f"  {json.dumps(theme_name)}: {{")
        entries = []
        for name, value in colours.items():
            floats = [max_float(value[index:index + 2]) for index in (1, 3, 5)] + [1.0]
            entries.append(f"    {json.dumps(name)}: [{', '.join(repr(f) for f in floats)}]")
        lines.append(",\n".join(entries))
        lines.append("  }" + ("," if theme_index == 0 else ""))
    lines.append("}")
    text = "\n".join(lines) + "\n"
    json.loads(text)  # a malformed file fails here, not in a Max patch
    return text


def main(arguments: list[str]) -> int:
    check_only = arguments == ["--check"]
    if arguments and not check_only:
        print("usage: derived_tokens.py [--check]", file=sys.stderr)
        return 2
    try:
        light_colours, dark_colours = read_colour_themes(TOKENS_CSS_PATH.read_text())
        check_launchpad_hues(light_colours, dark_colours)
        palette_status = check_led_values_against_palette_py()
    except TokenError as error:
        print(f"derived_tokens: FAILED (╯°□°)╯ {error}", file=sys.stderr)
        return 1
    expected_json = max_colours_json_text(light_colours, dark_colours)
    current_json = MAX_COLOURS_JSON_PATH.read_text() if MAX_COLOURS_JSON_PATH.is_file() else ""
    print(f"derived_tokens: {palette_status}")
    if check_only:
        if current_json != expected_json:
            print(f"derived_tokens: FAILED (╯°□°)╯ {MAX_COLOURS_JSON_PATH.relative_to(REPOSITORY_DIRECTORY)} is out of date "
                  "with tokens.css; run `python3 scripts/derived_tokens.py`", file=sys.stderr)
            return 1
        print(f"derived_tokens: tokens.css checks pass, max/2sl-colors.json is current ({len(light_colours)} colours) (^_^)")
        return 0
    MAX_COLOURS_JSON_PATH.write_text(expected_json)
    print(f"derived_tokens: wrote max/2sl-colors.json ({len(light_colours)} colours, "
          f"{'changed' if current_json != expected_json else 'unchanged'}) (^_^)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
